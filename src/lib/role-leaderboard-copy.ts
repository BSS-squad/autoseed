export function getRoleMetricCopy(
  key: string,
  methodology?: RoleLeaderboardMethodology | null
): MetricCopy | null {
  const publicMetric = methodology?.ranking.find((metric) => metric.key === key);
  if (publicMetric) {
    return {
      label: publicMetric.label,
      explanation: publicMetric.description
    };
  }
  return ROLE_METRIC_COPY[key] || null;
}

export function getAchievementCopy(
  code: string,
  methodology?: RoleLeaderboardMethodology | null
): AchievementCopy | null {
  const publicAchievement = methodology?.achievements.find(
    (achievement) => achievement.code === code
  );
  if (publicAchievement) {
    return {
      title: publicAchievement.title,
      description: publicAchievement.description
    };
  }
  return ACHIEVEMENT_COPY[code] || null;
}
